import { readFileSync, writeFileSync } from "node:fs";

const inputPath = process.argv[2] ?? "vendor/emoji/emojibase-data.json";
const outputPath = process.argv[3] ?? "crates/mb-core/src/emoji_generated.rs";
const groups = [
  "smileys",
  "people",
  "animals",
  "food",
  "travel",
  "activities",
  "objects",
  "symbols",
  "flags",
  "other",
];

const source = JSON.parse(readFileSync(inputPath, "utf8"));
if (!Array.isArray(source) || source.length < 1800) {
  throw new Error("emoji source is missing or unexpectedly small");
}

const rustString = (value) => JSON.stringify(value).replaceAll("\\u2028", "\\u{2028}").replaceAll("\\u2029", "\\u{2029}");
const entries = source.map((entry) => {
  if (typeof entry.emoji !== "string" || !Array.isArray(entry.shortcodes) || entry.shortcodes.length === 0) {
    throw new Error(`invalid emoji entry: ${JSON.stringify(entry)}`);
  }
  const shortcodes = entry.shortcodes.filter((value) => /^[a-z0-9_+\-]+$/i.test(value));
  if (shortcodes.length === 0) throw new Error(`emoji has no valid shortcode: ${entry.emoji}`);
  return {
    shortcode: shortcodes[0].toLowerCase(),
    aliases: shortcodes.slice(1).map((value) => value.toLowerCase()),
    glyph: entry.emoji,
    category: groups[entry.group] ?? "other",
    supportsSkinTone: Array.isArray(entry.skins) && entry.skins.length > 0,
    order: entry.order,
  };
}).sort((left, right) => left.order - right.order);

const duplicate = new Set();
for (const entry of entries) {
  for (const shortcode of [entry.shortcode, ...entry.aliases]) {
    if (duplicate.has(shortcode)) throw new Error(`duplicate shortcode: ${shortcode}`);
    duplicate.add(shortcode);
  }
}

const body = entries.map((entry) => `    Entry {
        shortcode: ${rustString(entry.shortcode)},
        glyph: ${rustString(entry.glyph)},
        category: ${rustString(entry.category)},
        aliases: &[${entry.aliases.map(rustString).join(", ")}],
        supports_skin_tone: ${entry.supportsSkinTone},
    },`).join("\n");
writeFileSync(outputPath, `// Generated by scripts/generate-emoji-catalog.mjs. Do not edit.\n\npub const ENTRIES: &[Entry] = &[\n${body}\n];\n`);
console.log(`generated ${entries.length} emoji entries and ${duplicate.size} shortcodes`);
